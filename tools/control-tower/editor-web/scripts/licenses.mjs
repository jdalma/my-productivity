// Writes THIRD-PARTY-LICENSES.md next to the built editor: every production package in package-lock.json
// (the set the bundle can draw from), its version, its license and the text of its license file.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const outDir = new URL('../../Sources/TowerCore/Resources/editor/', import.meta.url).pathname
if (!existsSync(outDir)) throw new Error(`no build output at ${outDir}: run vite build first`)
const lock = JSON.parse(readFileSync(new URL('../package-lock.json', import.meta.url), 'utf8'))

const sections = []
for (const [path, entry] of Object.entries(lock.packages)) {
  if (!path || entry.dev) continue
  const dir = new URL(`../${path}/`, import.meta.url).pathname
  const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length)
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f))
  const text = file ? readFileSync(join(dir, file), 'utf8').trim() : '(no license file in the package)'
  sections.push(`## ${name} ${entry.version}\n\nLicense: ${entry.license ?? 'not stated'}\n\n\`\`\`\n${text}\n\`\`\``)
}
sections.sort()
writeFileSync(join(outDir, 'THIRD-PARTY-LICENSES.md'),
  `# Third-party licenses: Control Tower editor\n\nGenerated by editor-web/scripts/licenses.mjs from package-lock.json, ${sections.length} packages.\n\n${sections.join('\n\n')}\n`)
console.log(`THIRD-PARTY-LICENSES.md: ${sections.length} packages`)
